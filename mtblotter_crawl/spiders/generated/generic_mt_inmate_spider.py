import scrapy
from services.ingestion.fetchers.generic_mt_inmate import fetch_generic_mt_bookings as _fetch

class GenericMtInmateSpider(scrapy.Spider):
    name = "generic_mt_inmate"
    def start_requests(self):
        yield scrapy.Request("data:,", callback=self.run, dont_filter=True)
    def run(self, response):
        try:
            records = _fetch()
        except TypeError:
            records = _fetch(None)
        for r in (records or []):
            yield {
                "county": getattr(r, "county", "generic_mt_inmate"),
                "county_slug": getattr(r, "county_slug", "generic_mt_inmate".replace("_inmate","")),
                "inmate_name": getattr(r, "name", None) or getattr(r, "inmate_name", None),
                "booking_date": getattr(r, "booking_date", None) or getattr(r, "booking_at", None),
                "charges": getattr(r, "charges", None) or getattr(r, "charges_summary", None),
                "source_url": getattr(r, "source_url", None),
            }
